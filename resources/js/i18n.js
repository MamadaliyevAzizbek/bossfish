export const i18nState = reactive({
    locale: localStorage.getItem('locale') || 'uz',
});

export const languages = [
    { code: 'uz', label: 'O‘zbek' },
    { code: 'uz_cyrl', label: 'Ўзбек' },
    { code: 'ru', label: 'Русский' },
    { code: 'zh', label: '中文' },
];

export function t(key, params = {}) {
    let text = messages[i18nState.locale]?.[key] ?? messages.uz[key] ?? key;
    Object.entries(params || {}).forEach(([name, value]) => {
        text = String(text).replaceAll(`{${name}}`, String(value));
    });
    return text;
}

export function setLocale(locale) {
    if (!messages[locale]) return;
    i18nState.locale = locale;
    localStorage.setItem('locale', locale);
    document.documentElement.lang = locale === 'ru' ? 'ru' : locale === 'zh' ? 'zh' : 'uz';
    if (window.axios) {
        window.axios.defaults.headers.common['X-Locale'] = locale;
    }
}

setLocale(i18nState.locale);
